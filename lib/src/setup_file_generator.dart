// Replace these sample values with your own database or backend settings.
// Do not commit real database passwords. Prefer --dart-define values.

import 'package:anysql/anysql.dart';

final class $className {
  const $className._();

  static AnySqlOptions get postgres => AnySqlOptions(
        config: AnySqlConfig.postgres(
          host: 'localhost',
          port: 5432,
          database: 'postgres_database',
