String generateAnySqlFirebaseStyleOptionsFile(AnySqlSetupInput input) {
  final placeholderInput = _placeholderInput(input);
  final contents = generateAnySqlOptionsFile(placeholderInput);
  final editHint = input.dialect == AnySqlDialect.sqlite
      ? 'Edit the generated values for your sqlite database.'
      : 'Edit the TODO values for your ${input.dialect.name} database.';

  return contents.replaceFirst(
    '// Generated by `dart run anysql configure`.\n'
        '// Do not commit real database passwords. Prefer --password-env with --dart-define.',
    '// Generated by `dart run anysql`.\n'
        '// $editHint\n'
        '// For Flutter apps, prefer connectBackendStore with a secure backend API.',
  );
}

String _configConstructor(AnySqlSetupInput input) {
  final values = switch (input.dialect) {
    AnySqlDialect.sqlite => <String>[
      _stringArgument('database', input.database),
    ],
    AnySqlDialect.custom => <String>[
      'dialect: AnySqlDialect.custom',
      if (input.host != null) _stringArgument('host', input.host!),
      if (input.port != null) 'port: ${input.port}',
      _stringArgument('database', input.database),
      if (input.username != null) _stringArgument('username', input.username!),
      if (input.passwordEnvironmentKey != null)
        "password: const String.fromEnvironment('${_escape(input.passwordEnvironmentKey!)}')",
      if (input.sslEnabled) 'sslEnabled: true',
    ],
    _ => <String>[
      if (input.host != null) _stringArgument('host', input.host!),
      if (input.port != null) 'port: ${input.port}',
      _stringArgument('database', input.database),
      if (input.username != null) _stringArgument('username', input.username!),
      if (input.passwordEnvironmentKey != null)
        "password: const String.fromEnvironment('${_escape(input.passwordEnvironmentKey!)}')",
      if (input.sslEnabled) 'sslEnabled: true',
    ],
  };

  final constructor = input.dialect == AnySqlDialect.custom
      ? 'AnySqlConfig'
      : 'AnySqlConfig.${input.dialect.name}';

  return '$constructor(\n'
      '          ${values.join(',\n          ')},\n'
      '        )';
}

AnySqlSetupInput _placeholderInput(AnySqlSetupInput input) {
  final database = switch (input.dialect) {
    AnySqlDialect.sqlite => 'app.sqlite',
    AnySqlDialect.postgres => 'TODO_POSTGRES_DATABASE',
    AnySqlDialect.mysql => 'TODO_MYSQL_DATABASE',
    AnySqlDialect.mongodb => 'TODO_MONGODB_DATABASE',
    AnySqlDialect.custom => 'TODO_DATABASE',
  };
  final username = switch (input.dialect) {
    AnySqlDialect.sqlite => null,
    AnySqlDialect.postgres => 'TODO_POSTGRES_USERNAME',
    AnySqlDialect.mysql => 'TODO_MYSQL_USERNAME',
    AnySqlDialect.mongodb => 'TODO_MONGODB_USERNAME',
    AnySqlDialect.custom => 'TODO_USERNAME',
  };

  return AnySqlSetupInput(
    dialect: input.dialect,
    host: input.dialect == AnySqlDialect.sqlite ? null : 'localhost',
    port: input.dialect == AnySqlDialect.sqlite
        ? null
        : _defaultPort(input.dialect),
    database: database,
    username: username,
    passwordEnvironmentKey: input.dialect == AnySqlDialect.sqlite
        ? null
        : _defaultPasswordKey(input.dialect),
    sslEnabled: false,
    backendUrl: input.backendUrl ?? 'https://api.example.com/anysql',
    backendHeaders: input.backendHeaders,
    className: input.className,
  );
}

int? _defaultPort(AnySqlDialect dialect) {
  return switch (dialect) {
    AnySqlDialect.postgres => 5432,
    AnySqlDialect.mysql => 3306,
    AnySqlDialect.mongodb => 27017,
    AnySqlDialect.sqlite || AnySqlDialect.custom => null,
  };
}

String? _defaultPasswordKey(AnySqlDialect dialect) {
  return switch (dialect) {
    AnySqlDialect.postgres => 'ANYSQL_POSTGRES_PASSWORD',
    AnySqlDialect.mysql => 'ANYSQL_MYSQL_PASSWORD',
    AnySqlDialect.mongodb => 'ANYSQL_MONGODB_PASSWORD',
    AnySqlDialect.sqlite || AnySqlDialect.custom => null,
  };
}

String _stringArgument(String name, String value) {
  final literal = "'${_escape(value)}'";
  if (value.startsWith('TODO_')) {
    return '$name: $literal, // TODO: replace with your value';
  }

  return '$name: $literal';
}

String _escape(String value) {
  final buffer = StringBuffer();

  for (final codeUnit in value.codeUnits) {
    switch (codeUnit) {
      case 0x08:
        buffer.write(r'\b');
      case 0x09:
        buffer.write(r'\t');
      case 0x0A:
        buffer.write(r'\n');
      case 0x0B:
        buffer.write(r'\v');
      case 0x0C:
        buffer.write(r'\f');
      case 0x0D:
        buffer.write(r'\r');
      case 0x24:
        buffer.write(r'\$');
      case 0x27:
        buffer.write(r"\'");
      case 0x5C:
        buffer.write(r'\\');
      default:
        if (codeUnit < 0x20) {
          buffer.write(r'\x');
          buffer.write(codeUnit.toRadixString(16).padLeft(2, '0'));
        } else {
          buffer.writeCharCode(codeUnit);
        }
    }
  }

  return buffer.toString();
}

String _stringMapLiteral(Map<String, String> values) {
  if (values.isEmpty) {
    return 'const {}';
  }

  final entries = values.entries.map(
    (entry) => "'${_escape(entry.key)}': '${_escape(entry.value)}'",
  );
  return 'const {${entries.join(', ')}}';
}
